class MfaScreen extends StatefulWidget {
  const MfaScreen({super.key});

  @override
  State<MfaScreen> createState() => _MfaScreenState();
}

class _MfaScreenState extends State<MfaScreen> {
  static const _len = 6;
  final _ctrls = List.generate(_len, (_) => TextEditingController());
  final _nodes = List.generate(_len, (_) => FocusNode());
  late final Timer _ticker;
  int _secondsLeft = _remaining();
  bool _trust = true;
  bool _loading = false;
  bool _verified = false;
  String? _factorId;
  Object? _loadError;

  // Authenticator codes rotate on 30s boundaries of the wall clock.
  static int _remaining() => 30 - (DateTime.now().millisecondsSinceEpoch ~/ 1000) % 30;

  @override
  void initState() {
    super.initState();
    _ticker = Timer.periodic(const Duration(seconds: 1), (_) => setState(() => _secondsLeft = _remaining()));
    _loadFactor();
  }

  Future<void> _loadFactor() async {
    try {
      final id = await authRepo.verifiedTotpFactorId();
      if (mounted) setState(() => _factorId = id);
    } catch (e) {
      if (mounted) setState(() => _loadError = e);
    }
  }

  @override
  void dispose() {
    _ticker.cancel();
    for (final c in _ctrls) {
      c.dispose();
    }
    for (final n in _nodes) {
      n.dispose();
    }
    super.dispose();
  }

  String get _code => _ctrls.map((c) => c.text).join();

  void _onChanged(int i, String value) {
    final digits = value.replaceAll(RegExp(r'\D'), '');
    if (digits.isEmpty) {
      _ctrls[i].text = '';
      return;
    }
    // Multiple digits at once = paste or autofill: spread across the boxes.
    for (var k = 0; k < digits.length && i + k < _len; k++) {
      _ctrls[i + k].text = digits[k];
    }
    final next = (i + digits.length).clamp(0, _len - 1);
    _nodes[next].requestFocus();
    if (_code.length == _len) _verify();
  }

  KeyEventResult _onKey(int i, KeyEvent e) {
    if (e is KeyDownEvent && e.logicalKey == LogicalKeyboardKey.backspace && _ctrls[i].text.isEmpty && i > 0) {
      _ctrls[i - 1].clear();
      _nodes[i - 1].requestFocus();
      return KeyEventResult.handled;
    }
    return KeyEventResult.ignored;
  }

  Future<void> _verify() async {
    if (_loading || _verified) return;
    if (_code.length != _len) {
      showError(context, 'Enter the 6-digit code.');
      return;
    }
    final factor = _factorId;
    if (factor == null) {
      showError(context, 'No authenticator is enrolled for this account.');
      return;
    }
    setState(() => _loading = true);
    try {
      await authRepo.verifyTotp(factor, _code);
      if (!mounted) return;
      setState(() => _verified = true);
      await Future<void>.delayed(const Duration(milliseconds: 600));
      if (mounted) context.go(Routes.tenants);
    } on AuthException catch (e) {
      if (!mounted) return;
      showError(context, e.message);
      for (final c in _ctrls) {
        c.clear();
      }
      _nodes.first.requestFocus();
    } catch (e) {
      if (mounted) showError(context, e);
    } finally {
      if (mounted) setState(() => _loading = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    return AuthScaffold(
      child: Column(
        mainAxisSize: MainAxisSize.min,
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Center(
            child: Container(
              width: 64,
              height: 64,
              decoration: BoxDecoration(color: C.primaryContainer.withValues(alpha: 0.15), borderRadius: BorderRadius.circular(12)),
              child: const Icon(Icons.shield, color: C.primary, size: 34),
            ),
          ),
          const SizedBox(height: 12),
          const Center(child: Pill('256-Bit SSL Encrypted Verification', icon: Icons.lock_outline, fg: C.tertiary)),
          const SizedBox(height: 20),
          Text('Two-Factor Authentication', style: T.headlineLg, textAlign: TextAlign.center),
          const SizedBox(height: 4),
          Text(
            'Enter the 6-digit security code generated by your Google Authenticator app to verify your identity.',
            style: T.bodyMd.copyWith(color: C.onSurfaceVariant, height: 1.6),
            textAlign: TextAlign.center,
          ),
          const SizedBox(height: 24),
          if (_loadError != null)
            ErrorRetry(error: _loadError!, onRetry: () {
              setState(() => _loadError = null);
              _loadFactor();
            })
          else ...[
            Row(mainAxisAlignment: MainAxisAlignment.center, children: [
              for (var i = 0; i < _len; i++) ...[
                if (i == 3)
                  Container(width: 8, height: 2, margin: const EdgeInsets.symmetric(horizontal: 4), color: C.outlineVariant),
                _OtpBox(controller: _ctrls[i], node: _nodes[i], autofocus: i == 0, onChanged: (v) => _onChanged(i, v), onKey: (e) => _onKey(i, e)),
                if (i < _len - 1 && i != 2) const SizedBox(width: 8),
              ],
            ]),
            const SizedBox(height: 20),
            Center(
              child: Container(
                padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 6),
                decoration: BoxDecoration(color: C.surfaceLow, borderRadius: BorderRadius.circular(999)),
                child: Row(mainAxisSize: MainAxisSize.min, children: [
                  SizedBox(
                    width: 16,
                    height: 16,
                    child: CircularProgressIndicator(value: _secondsLeft / 30, strokeWidth: 2.5, color: C.primary, backgroundColor: C.surfaceHighest),
                  ),
                  const SizedBox(width: 8),
                  Text('Code refreshes in ', style: T.labelMd.copyWith(color: C.onSurfaceVariant)),
                  Text('${_secondsLeft}s', style: T.labelMd.copyWith(color: C.primary, fontWeight: FontWeight.w700)),
                ]),
              ),
            ),
            const SizedBox(height: 16),
            Center(
              child: InkWell(
                borderRadius: BorderRadius.circular(8),
                onTap: () => setState(() => _trust = !_trust),
                child: Padding(
                  padding: const EdgeInsets.all(4),
                  child: Row(mainAxisSize: MainAxisSize.min, children: [
                    Container(
                      width: 16,
                      height: 16,
                      decoration: BoxDecoration(color: _trust ? C.primary : C.surfaceHigh, borderRadius: BorderRadius.circular(4)),
                      child: _trust ? const Icon(Icons.check, size: 12, color: Colors.white) : null,
                    ),
                    const SizedBox(width: 8),
                    Text('Trust this device for 30 days', style: T.bodyMd.copyWith(color: C.onSurfaceVariant)),
                  ]),
                ),
              ),
            ),
            const SizedBox(height: 20),
            PrimaryButton(
              label: _verified ? 'Authenticated!' : 'Verify & Continue',
              icon: _verified ? Icons.verified : Icons.arrow_forward,
              color: _verified ? C.tertiary : C.primary,
              loading: _loading,
              onPressed: _factorId == null ? null : _verify,
            ),
            if (_factorId == null && _loadError == null) ...[
              const SizedBox(height: 8),
              Text('Checking your authenticator…', style: T.bodySm.copyWith(color: C.secondary), textAlign: TextAlign.center),
            ],
          ],
          const SizedBox(height: 20),
          Container(
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(color: C.surfaceLow.withValues(alpha: 0.6), borderRadius: BorderRadius.circular(12)),
            child: Column(children: [
              Row(mainAxisAlignment: MainAxisAlignment.center, children: [
                const Icon(Icons.key, size: 16, color: C.primary),
                const SizedBox(width: 6),
                Flexible(child: Text('Try another way (SMS backup code, Security key)', style: T.labelMd.copyWith(color: C.primary))),
              ]),
              const SizedBox(height: 8),
              Wrap(alignment: WrapAlignment.center, children: [
                Text('Need help with 2FA? ', style: T.bodySm),
                Text('Contact your Reseller Admin', style: T.labelMd.copyWith(color: C.primary)),
              ]),
            ]),
          ),
          const SizedBox(height: 16),
          Row(mainAxisAlignment: MainAxisAlignment.spaceBetween, children: [
            Row(children: [
              const Icon(Icons.domain, size: 14, color: C.outline),
              const SizedBox(width: 4),
              Text('BizNest Hub Auth Gateway', style: T.labelSm.copyWith(color: C.outline)),
            ]),
            TextButton(onPressed: authRepo.signOut, child: Text('Cancel & sign out', style: T.labelSm.copyWith(color: C.primary))),
          ]),
        ],
      ),
    );
  }
}

class _OtpBox extends StatelessWidget {
  const _OtpBox({required this.controller, required this.node, required this.onChanged, required this.onKey, this.autofocus = false});
  final TextEditingController controller;
  final FocusNode node;
  final ValueChanged<String> onChanged;
  final KeyEventResult Function(KeyEvent) onKey;
  final bool autofocus;

  @override
  Widget build(BuildContext context) => SizedBox(
        width: 44,
        height: 56,
        child: Focus(
          onKeyEvent: (_, e) => onKey(e),
          child: TextField(
            controller: controller,
            focusNode: node,
            autofocus: autofocus,
            textAlign: TextAlign.center,
            keyboardType: TextInputType.number,
            style: T.headlineMd,
            inputFormatters: [FilteringTextInputFormatter.digitsOnly],
            onChanged: onChanged,
            decoration: fieldDecoration().copyWith(contentPadding: EdgeInsets.zero),
          ),
        ),
      );
}
